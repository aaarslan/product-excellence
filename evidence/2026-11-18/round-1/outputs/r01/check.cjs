const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
(async()=>{
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const context=await browser.newContext({viewport:{width:1365,height:1100},offline:true});
const page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(String(e)));
const file='file://'+path.resolve('index.html');
await page.goto(file);
await page.screenshot({path:'desktop.png',fullPage:true});
console.log('Initial heading',await page.locator('h1:visible').textContent());
const p=await page.locator('#character').textContent(), q=await page.locator('#place').textContent(), t=await page.locator('#trouble').textContent();
await page.getByRole('button',{name:'Swap only the complication',exact:true}).click();
if(await page.locator('#character').textContent()!==p || await page.locator('#place').textContent()!==q || await page.locator('#trouble').textContent()===t) throw Error('Single swap failed');
await page.locator('#title').fill('The Tiny Storm');
const story='Mara wanted a quiet day. A tiny storm followed her home. She gave it a cup of tea. It rained politely in the sink.';
await page.locator('#text').fill(story);
await page.reload();
if(await page.locator('#text').inputValue()!==story) throw Error('Draft reload failed');
await page.getByRole('button',{name:'Ready to read'}).click();
if(await page.locator('#reader-text').textContent()!==story) throw Error('Reading text mismatch');
await page.screenshot({path:'reader.png',fullPage:true});
await page.getByRole('button',{name:'Make another story'}).click();
await page.locator('#text').fill('An unfinished adventure with an ending still to come.');
await page.getByRole('button',{name:'Start another story'}).click();
await page.getByRole('button',{name:/Your shelf/}).click();
if(await page.locator('.book').count()!==2) throw Error('Shelf preservation failed');
await page.getByRole('button',{name:'Read The Tiny Storm',exact:true}).click();
await page.getByRole('button',{name:'Move to recently removed'}).click();
await page.getByRole('button',{name:/Recently removed 1/}).click();
await page.getByRole('button',{name:'Restore The Tiny Storm',exact:true}).click();
await page.getByRole('button',{name:'Back to kept stories'}).click();
await page.locator('#search').fill('tiny storm');
if(await page.locator('.book').count()!==1) throw Error('Search failed');
await page.locator('#search').fill('');
await page.screenshot({path:'shelf.png',fullPage:true});
const sample=JSON.parse(fs.readFileSync('sample-storage.json','utf8'));
await page.evaluate(data=>{localStorage.clear();for(const [k,v] of Object.entries(data))localStorage.setItem(k,JSON.stringify(v));},sample);
await page.reload();
if(await page.locator('#text').inputValue()!==sample['storybreak.draft.v1'].text) throw Error('Legacy draft text lost');
if(await page.locator('#character').textContent()!=='a nervous dragon') throw Error('Legacy prompt changed');
await page.getByRole('button',{name:/Your shelf/}).click();
await page.getByRole('button',{name:'Read A Pocket of Moonlight',exact:true}).click();
if(await page.locator('#reader-text').textContent()!==sample['storybreak.stories.v1'][1].text) throw Error('Legacy story changed');
if(!(await page.locator('#reader-ingredients').textContent()).includes('an umbrella repairer')) throw Error('Old prompt lost');
await page.getByRole('button',{name:'Make a story',exact:true}).click();
if(await page.locator('#text').inputValue()!==sample['storybreak.draft.v1'].text) throw Error('Reading overwrote draft');
await page.getByText('Make it a timed round',{exact:true}).click();
await page.getByRole('button',{name:'Start',exact:true}).click();
await page.waitForTimeout(1200);
await page.getByRole('button',{name:'Pause',exact:true}).click();
if(await page.locator('#time').textContent()==='10:00') throw Error('Clock did not run');
await page.setViewportSize({width:375,height:812});
await page.screenshot({path:'mobile.png',fullPage:true});
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
if(overflow) throw Error('Mobile overflow');
await page.getByRole('button',{name:'Shuffle all three'}).click();
await page.keyboard.press('Escape');
if(await page.locator('#shuffle-dialog').isVisible()) throw Error('Keyboard modal cancel failed');
console.log('PASS: offline file load, one-card swap, draft persistence, finish/read, preserved drafts, restore, search, legacy data, optional timer, mobile width, Escape modal.');
console.log('Console errors:',JSON.stringify(errors));
await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
